CREATE DATABASE IF NOT EXISTS face_sud;
USE face_sud;

--TABLE USERS (USUARIOS)
CREATE TABLE IF NOT EXISTS users(
    user_id INT PRIMARY KEY AUTO_INCREMENT,
    name VARCHAR(20) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    member_num INT(11) NOT NULL UNIQUE,
    hierarchy VARCHAR(100),
    register_date DATETIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP

);

--TABLE POSTS (POSTEOS)
CREATE TABLE IF NOT EXISTS posts(
    post_id INT PRIMARY KEY AUTOINCREMENT,
    user_id INT NOT NULL,
    text VARCHAR NOT NULL,
    date_posted DATETIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(user_id)
);

--TABLE COMMENTS (COMENTARIOS)
CREATE TABLE IF NOT EXISTS comments(
    comments_id INT PRIMARY KEY AUTOINCREMENT,
    user_id INT NOT NULL,
    post_id INT NOT NULL,
    text_comment TEXT NOT NULL,
    date_commented DATETIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (post_id) REFERENCES posts(post_id),
    FOREIGN KEY (user_id) REFERENCES users(user_id)
);

--TABLE  POST_LIKES (LIKES EN LOS POSTEOS)
CREATE TABLE IF NOT EXISTS likes(
    like_id INT PRIMARY KEY AUTOINCREMENT,
    user_id INT NOT NULL,
    post_id INT NOT NULL,
    liked_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(user_id),
    FOREIGN KEY (post_id) REFERENCES posts(post_id),
    UNIQUE(user_id, post_id)
);