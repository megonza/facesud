CREATE DATABASE IF NO EXISTS face_sud;
USE face_sud;

CREATE TABLE IF NOT EXISTS users(
    user_id INT PRIMARY KEY AUTOINCREMENT,
    name VARHCAR(20) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    password VARHCAR(255) NOT NULL,
    member_num INT(11) NOT NULL UNIQUE,
    hierarchy VARCHAR(100),
    register_date DATETIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP

)